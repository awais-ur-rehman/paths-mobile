"""Generate the supported scalar DTO subset from the pinned OpenAPI document.
Unsupported schemas fail explicitly; extend the generator with contract tests as APIs grow.
"""
from pathlib import Path
import hashlib,json,sys
root=Path(__file__).resolve().parents[1]
source=Path(sys.argv[1]) if len(sys.argv)>1 else root/'openapi/paths.v1.json'
raw=source.read_bytes();contract=json.loads(raw)
lines=['// Generated by tools/generate_api_contract.py; do not edit.',f"const apiContractVersion = '{contract['info']['version']}';",f"const apiContractSha256 = '{hashlib.sha256(raw).hexdigest()}';"]
for name,schema in contract['components']['schemas'].items():
 if schema.get('type')!='object':raise ValueError(f'Unsupported schema {name}')
 properties=schema.get('properties',{});required=set(schema.get('required',[]))
 if set(properties)!=required:raise ValueError(f'Optional fields need explicit support: {name}')
 for field,value in properties.items():
  if value.get('type')!='string':raise ValueError(f'Unsupported field {name}.{field}')
 lines += [f'final class {name} {{',f"  const {name}({{{', '.join('required this.'+f for f in properties)}}});"]
 lines += [f'  final String {field};' for field in properties]
 lines += [f'  factory {name}.fromJson(Map<String, dynamic> json) {{']
 for field,value in properties.items():
  lines += [f"    final {field} = json['{field}'];",f"    if ({field} is! String) {{ throw const FormatException('Invalid {name}'); }}"]
  if 'enum' in value:lines += [f"    if (!const {value['enum']}.contains({field})) {{ throw const FormatException('Unsupported {field}'); }}"]
 lines += [f"    return {name}({', '.join(f'{f}: {f}' for f in properties)});",'  }','}']
(root/'lib/core/network/generated/api_contract.dart').write_text('\n'.join(lines)+'\n')
print('Generated Dart DTOs from contract '+contract['info']['version'])
