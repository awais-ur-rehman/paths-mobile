#!/usr/bin/env python3
"""Compile original path-only SVG masters into Flutter vector geometry, offline."""
from pathlib import Path
import re
import subprocess
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
NAMES = ('home', 'likes', 'chats', 'profile', 'plus', 'verified', 'unverified', 'search', 'back', 'send', 'more', 'settings', 'lock', 'globe', 'location', 'bell', 'block', 'key', 'logout', 'trash', 'chevronRight', 'review')
COMMANDS = {'M': ('moveTo', 2), 'L': ('lineTo', 2),
            'C': ('cubicTo', 6), 'Q': ('quadraticBezierTo', 4), 'Z': ('close', 0)}


def compile_path(data):
    tokens = re.findall(r'[A-Za-z]|-?\d+(?:\.\d+)?', data)
    if re.sub(r'[\s,]', '', data) != ''.join(tokens):
        raise ValueError('Unsupported SVG path syntax')
    lines = []
    index = 0
    while index < len(tokens):
        command = tokens[index]
        if command not in COMMANDS:
            raise ValueError(f'Unsupported SVG command {command}')
        method, count = COMMANDS[command]
        values = tokens[index + 1:index + 1 + count]
        if len(values) != count or any(re.fullmatch(r'-?\d+(?:\.\d+)?', v) is None for v in values):
            raise ValueError('Incomplete SVG command')
        lines.append(f"    ..{method}({', '.join(values)})")
        index += count + 1
    return '\n'.join(lines)


parts = ["// Generated by tools/export_icons.py from assets/icons/*.svg.\n"
         "import 'dart:ui';\n\nenum PathsIconName { " + ', '.join(NAMES) + " }\n",
         'const pathsIconStrokeWidth = 1.8;\n',
         'final pathsIconGeometry = <PathsIconName, Path>{']
for name in NAMES:
    svg = ET.parse(ROOT / f'assets/icons/{name}.svg').getroot()
    if svg.attrib != {'viewBox': '0 0 24 24'}:
        raise ValueError('Expected 24-unit viewBox')
    paths = []
    for element in svg:
        if element.tag.endswith('}title'):
            continue
        if set(element.attrib) != {'d', 'fill', 'stroke', 'stroke-width', 'stroke-linecap', 'stroke-linejoin'} or element.attrib.get('stroke') != '#101418' or not element.tag.endswith('}path') or element.attrib.get('stroke-width') != '1.8' or element.attrib.get('stroke-linecap') != 'round' or element.attrib.get('stroke-linejoin') != 'round' or element.attrib.get('fill') != 'none':
            raise ValueError('Only unfilled, rounded 1.8-unit paths are supported')
        paths.append(element.attrib['d'])
    if not paths:
        raise ValueError('Empty icon')
    parts.append(f'  PathsIconName.{name}: Path()\n' + compile_path(' '.join(paths)) + ',')
parts.append('};\n')
output = ROOT / 'lib/shared/widgets/generated/paths_icon_geometry.dart'
output.write_text('\n'.join(parts))
subprocess.run(['dart', 'format', str(output)], check=True)
